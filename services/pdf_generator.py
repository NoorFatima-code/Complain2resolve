"""Create locally downloadable English or Urdu application PDFs."""

import os
import re
from pathlib import Path
from uuid import uuid4
from xml.sax.saxutils import escape

from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

from services.application_generator import URDU

OUTPUT_DIR = Path(__file__).resolve().parent.parent / "output" / "generated_pdfs"


def _font_for_language(language: str) -> str:
    if language != URDU:
        return "Helvetica"
    candidates = [
        os.getenv("SHIKAYAT_URDU_FONT"),
        r"C:\Windows\Fonts\arial.ttf",
        r"C:\Windows\Fonts\tahoma.ttf",
        "/usr/share/fonts/truetype/noto/NotoNaskhArabic-Regular.ttf",
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    ]
    for candidate in candidates:
        if candidate and Path(candidate).is_file():
            if "ShikayatUrdu" not in pdfmetrics.getRegisteredFontNames():
                pdfmetrics.registerFont(TTFont("ShikayatUrdu", candidate))
            return "ShikayatUrdu"
    raise RuntimeError(
        "No Urdu-capable TrueType font found. Set SHIKAYAT_URDU_FONT to a font file "
        "with Arabic-script glyphs (for example, Noto Naskh Arabic)."
    )


def _prepare_for_pdf(text: str, language: str) -> str:
    if language != URDU:
        return text
    try:
        import arabic_reshaper
        from bidi.algorithm import get_display
    except ImportError as exc:
        raise RuntimeError(
            "Urdu PDF support requires arabic-reshaper and python-bidi."
        ) from exc
    return "\n".join(
        get_display(arabic_reshaper.reshape(line))
        if re.search(r"[\u0600-\u06ff]", line)
        else line
        for line in text.splitlines()
    )


def generate_pdf(application: str, language: str = "English") -> str:
    """Write a downloadable PDF under output/generated_pdfs and return its path."""
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    target = OUTPUT_DIR / f"application-{uuid4().hex}.pdf"
    font_name = _font_for_language(language)
    styles = getSampleStyleSheet()
    body = ParagraphStyle(
        "ApplicationBody",
        parent=styles["BodyText"],
        fontName=font_name,
        fontSize=11,
        leading=17,
        spaceAfter=7,
    )
    story = []
    for line in _prepare_for_pdf(application, language).splitlines():
        story.append(Paragraph(escape(line) or "&nbsp;", body))
        story.append(Spacer(1, 2 * mm))
    document = SimpleDocTemplate(
        str(target),
        pagesize=A4,
        rightMargin=20 * mm,
        leftMargin=20 * mm,
        topMargin=20 * mm,
        bottomMargin=20 * mm,
        title="scomplain2resolve application",
    )
    document.build(story)
    return str(target)


def clear_previous_pdfs() -> None:
    """Remove only PDFs generated by this app when a new app process starts."""
    if not OUTPUT_DIR.is_dir():
        return
    for path in OUTPUT_DIR.glob("application-*.pdf"):
        path.unlink()
